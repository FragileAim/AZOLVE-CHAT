import { spawn } from 'node:child_process';
import WebSocket from 'ws';
const BIN='/root/.cache/ms-playwright/chromium_headless_shell-1217/chrome-headless-shell-linux64/chrome-headless-shell';
const p=spawn(BIN,['--headless','--no-sandbox','--disable-gpu','--remote-debugging-port=9339','about:blank'],{stdio:'ignore'});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
await sleep(2500);
const list=await (await fetch('http://127.0.0.1:9339/json/list')).json();
const sock=new WebSocket(list.find(t=>t.type==='page').webSocketDebuggerUrl);
let id=0;const pend=new Map();
sock.on('message',m=>{const d=JSON.parse(m);if(d.id&&pend.has(d.id)){pend.get(d.id)(d.result);pend.delete(d.id);}});
await new Promise(r=>sock.on('open',r));
const send=(m,params={})=>new Promise(r=>{const i=++id;pend.set(i,r);sock.send(JSON.stringify({id:i,method:m,params}));});
const ev=async e=>{const r=await send('Runtime.evaluate',{expression:e,returnByValue:true,awaitPromise:true});return r.result?.value;};
await send('Runtime.enable');await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:2,mobile:true});
await send('Page.navigate',{url:'https://azolve-chat.onrender.com/#/auth'});
await sleep(7000);
await ev(`(()=>{const b=[...document.querySelectorAll('button,a')].find(x=>/already have an account/i.test(x.innerText));b&&b.click();})()`);
await sleep(2500);
console.log('scripts:',await ev(`JSON.stringify(performance.getEntriesByType('resource').filter(r=>r.name.includes('/assets/')).map(r=>r.name.split('/').pop()))`));
console.log('bundle has start path:',await ev(`(async()=>{const s=[...document.querySelectorAll('script[src]')].map(x=>x.src);const r=await fetch(s[s.length-1]);const t=await r.text();return 'len='+t.length+' hasOauthStart='+t.includes('oauth/google/start')+' hasOldGate='+t.includes('not configured on this server yet');})()`));
console.log('form?',await ev(`(()=>{const b=[...document.querySelectorAll('button')].find(x=>/^google$/i.test(x.innerText.trim()));return 'inForm='+!!b.closest('form')+' type='+b.type;})()`));
// attach capture listener then click
await ev(`window.__hits=[];document.addEventListener('click',e=>{window.__hits.push('doc-click:'+e.target.tagName+':'+e.target.innerText.trim().slice(0,15));},true);`);
console.log('click:',await ev(`(()=>{const b=[...document.querySelectorAll('button')].find(x=>/^google$/i.test(x.innerText.trim()));b.click();return 'ok';})()`));
await sleep(4000);
console.log('hits:',await ev(`JSON.stringify(window.__hits)`));
console.log('URL:',await ev(`location.href`));
p.kill();process.exit(0);
