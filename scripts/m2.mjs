import { spawn } from 'node:child_process';
import WebSocket from 'ws';
import fs from 'node:fs';
const CHROME='/root/.cache/ms-playwright/chromium_headless_shell-1217/chrome-headless-shell-linux64/chrome-headless-shell';
const PORT=9423, BASE='http://localhost:4500';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const chrome=spawn(CHROME,['--headless=new',`--remote-debugging-port=${PORT}`,'--no-sandbox','--disable-gpu','about:blank']);
await sleep(1300);
const list=await (await fetch(`http://127.0.0.1:${PORT}/json`)).json();
const ws=new WebSocket(list[0].webSocketDebuggerUrl);
let id=0;const pend=new Map();
ws.on('message',d=>{const m=JSON.parse(d);if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id);}});
await new Promise(r=>ws.on('open',r));
const send=(m,p={})=>new Promise(r=>{const i=++id;pend.set(i,r);ws.send(JSON.stringify({id:i,method:m,params:p}));});
const ev=async e=>(await send('Runtime.evaluate',{expression:e,returnByValue:true})).result?.result?.value;
await send('Page.enable');await send('Runtime.enable');
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:2,mobile:true});
await send('Page.navigate',{url:BASE+'/'});await sleep(600);
await ev(`localStorage.clear();localStorage.setItem('azolve.theme','light')`);
await send('Page.navigate',{url:BASE+'/'});await sleep(1800);
await ev(`[...document.querySelectorAll('button')].find(b=>/Get started/i.test(b.textContent))?.click()`);
await sleep(500);
await ev(`[...document.querySelectorAll('.auth-mode-switch button')].find(b=>/Create account/i.test(b.textContent))?.click()`);
await sleep(600);
console.log('create', await ev(`JSON.stringify({scrollH:document.documentElement.scrollHeight,vh:innerHeight,btn:Math.round([...document.querySelectorAll('button')].find(b=>/Continue/i.test(b.textContent))?.getBoundingClientRect().bottom||-1)})`));
const s1=await send('Page.captureScreenshot',{format:'png'});
fs.writeFileSync('/workspace/.screenshots/auth-create-390.png',Buffer.from(s1.result.data,'base64'));
// back to hero
await ev(`document.querySelector('.auth-mobile-back button')?.click()`);
await sleep(600);
console.log('back-to-hero', await ev(`JSON.stringify({hero:getComputedStyle(document.querySelector('.auth-mobile-hero')).display,panel:getComputedStyle(document.querySelector('.auth-panel')).display,scrollH:document.documentElement.scrollHeight,vh:innerHeight})`));
const s2=await send('Page.captureScreenshot',{format:'png'});
fs.writeFileSync('/workspace/.screenshots/auth-hero-390.png',Buffer.from(s2.result.data,'base64'));
ws.close();chrome.kill();
